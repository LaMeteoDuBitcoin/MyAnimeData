st.markdown("""
## Données utilisées
Les données utilisées dans cette application proviennent de l'API de MyAnimeList, une plateforme populaire pour les amateurs d'anime et de manga. L'API permet d'accéder à une vaste base de données d'anime, de manga, de personnages, de studios, et bien plus encore.  
Les données sont récupérées en temps réel, ce qui garantit que les informations affichées sont toujours à jour. Les utilisateurs peuvent explorer différentes catégories d'anime, consulter les détails des séries, et analyser les tendances du moment.
""")